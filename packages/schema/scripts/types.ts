// Writes generated/types.ts: exact TypeScript types generated from the JSON
// Schema. TypeBox's own inferred types fall back to `any` deep inside the
// recursive grammar, so code should import these instead.

import { writeFileSync, mkdirSync } from 'node:fs'
import { compile } from 'json-schema-to-typescript'
import { jsonSchema } from '../src/index.ts'

const doc = jsonSchema({ declared: true }) as any
// Generate one named type per declaration, not one big entity union.
const names = Object.keys(doc.$defs)
const root = {
  title: 'Declarations', type: 'object' as const, additionalProperties: false,
  properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${n}` }])),
  $defs: Object.fromEntries(names.map((n) => [n, { ...doc.$defs[n], title: n }])),
}
const ts = await compile(root, 'Declarations', {
  bannerComment: '// Generated by scripts/types.ts from the schema. Do not edit.',
  unreachableDefinitions: true,
  additionalProperties: false,
  format: false,
  strictIndexSignatures: true,
})
const out = new URL('../generated/', import.meta.url)
mkdirSync(out, { recursive: true })
writeFileSync(new URL('types.ts', out), ts)
console.log('wrote generated/types.ts', ts.length, 'chars')
